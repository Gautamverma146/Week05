package com.tit.day01.advanced_problems.csv_data_to_java_objects;

public class Student {
    //attribute
    private String id;
    private String name;
    private int age;
    private double marks;

    public String getId() {
        return id;
    }
    public String getName() {
        return name;
    }
    public int getAge() {
        return age;
    }
    public double getMarks() {
        return marks;
    }


}
